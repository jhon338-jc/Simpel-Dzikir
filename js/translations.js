// Language Manager
class LanguageManager {
    constructor() {
        this.currentLang = localStorage.getItem('appLanguage') || 'id';
        this.init();
    }
    
    init() {
        this.applyLanguage();
        this.setupLanguageSelector();
    }
    
    translate(key) {
        return translations[this.currentLang]?.[key] || translations['id'][key] || key;
    }
    
    applyLanguage() {
        // Update all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translated = this.translate(key);
            if (translated && translated !== key) {
                el.textContent = translated;
            }
        });
        
        // Update placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.placeholder = this.translate(key);
        });
        
        // Update select options
        document.querySelectorAll('[data-i18n-option]').forEach(option => {
            const key = option.getAttribute('data-i18n-option');
            if (key) {
                option.textContent = this.translate(key);
            }
        });
        
        // Update title
        const titleKey = document.querySelector('title')?.getAttribute('data-i18n-title');
        if (titleKey) {
            document.title = this.translate(titleKey);
        }
    }
    
    setupLanguageSelector() {
        const langSelect = document.getElementById('language');
        if (langSelect) {
            langSelect.value = this.currentLang;
            langSelect.addEventListener('change', (e) => {
                this.currentLang = e.target.value;
                localStorage.setItem('appLanguage', this.currentLang);
                this.applyLanguage();
            });
        }
    }
}

// Font Size Manager
class FontSizeManager {
    constructor() {
        this.sizes = {
            small: { arab: '1.1rem', latin: '0.85rem', text: '13px' },
            medium: { arab: '1.3rem', latin: '1rem', text: '16px' },
            large: { arab: '1.6rem', latin: '1.2rem', text: '18px' },
            xlarge: { arab: '2rem', latin: '1.4rem', text: '20px' }
        };
        this.currentSize = localStorage.getItem('fontSize') || 'medium';
        this.init();
    }
    
    init() {
        this.applyFontSize();
        this.setupFontSelector();
    }
    
    applyFontSize() {
        const size = this.sizes[this.currentSize];
        if (!size) return;
        
        document.documentElement.style.setProperty('--font-size-base', size.text);
        document.documentElement.style.setProperty('--font-size-arabic', size.arab);
        document.documentElement.style.setProperty('--font-size-latin', size.latin);
        
        document.querySelectorAll('.arab-text, .arabic-dzikir, .step-arabic, .arab-preview').forEach(el => {
            el.style.fontSize = size.arab;
        });
        
        document.querySelectorAll('.latin-text, .latin-dzikir, .latin-preview').forEach(el => {
            el.style.fontSize = size.latin;
        });
        
        document.querySelectorAll('.meaning, .meaning-dzikir, .meaning-preview').forEach(el => {
            el.style.fontSize = size.text;
        });
        
        document.body.style.fontSize = size.text;
    }
    
    setupFontSelector() {
        const fontSelect = document.getElementById('fontSize');
        if (fontSelect) {
            fontSelect.value = this.currentSize;
            fontSelect.addEventListener('change', (e) => {
                this.currentSize = e.target.value;
                localStorage.setItem('fontSize', this.currentSize);
                this.applyFontSize();
            });
        }
    }
}

// Settings Reset Function
function resetAllSettings() {
    localStorage.clear();
    
    const defaultSettings = {
        fontSize: 'medium',
        appLanguage: 'id',
        darkMode: 'false',
        audioVolume: '70',
        autoPlay: 'false',
        adzanNotif: 'false',
        dzikirNotif: 'false'
    };
    
    Object.keys(defaultSettings).forEach(key => {
        localStorage.setItem(key, defaultSettings[key]);
    });
    
    const msg = document.createElement('div');
    msg.className = 'toast-message';
    msg.innerHTML = '<i class="fas fa-check-circle"></i> Pengaturan berhasil direset!';
    document.body.appendChild(msg);
    
    setTimeout(() => {
        location.reload();
    }, 1500);
}

// Initialize when DOM ready
document.addEventListener('DOMContentLoaded', () => {
    const langManager = new LanguageManager();
    const fontManager = new FontSizeManager();
    
    const resetBtn = document.getElementById('resetSettings');
    if (resetBtn) {
        resetBtn.addEventListener('click', resetAllSettings);
    }
    
    const darkToggle = document.getElementById('darkMode');
    if (darkToggle) {
        darkToggle.checked = localStorage.getItem('darkMode') === 'true';
        darkToggle.addEventListener('change', (e) => {
            if (window.themeManager) {
                window.themeManager.toggleDarkMode();
            } else {
                if (e.target.checked) {
                    document.body.classList.add('dark-mode');
                    localStorage.setItem('darkMode', 'true');
                } else {
                    document.body.classList.remove('dark-mode');
                    localStorage.setItem('darkMode', 'false');
                }
            }
        });
    }
    
    const volumeSlider = document.getElementById('volumeSlider');
    if (volumeSlider) {
        volumeSlider.value = localStorage.getItem('audioVolume') || 70;
        const volumeValue = document.getElementById('volumeValue');
        if (volumeValue) {
            volumeValue.textContent = volumeSlider.value + '%';
        }
        volumeSlider.addEventListener('input', (e) => {
            const val = e.target.value;
            if (volumeValue) volumeValue.textContent = val + '%';
            localStorage.setItem('audioVolume', val);
            if (window.audioManager) audioManager.setVolume(val);
        });
    }
});

// Simple Theme Manager
class ThemeManager {
    constructor() {
        this.darkMode = localStorage.getItem('darkMode') === 'true';
        this.init();
    }
    
    init() {
        if (this.darkMode) {
            document.body.classList.add('dark-mode');
        }
    }
    
    toggleDarkMode() {
        this.darkMode = !this.darkMode;
        localStorage.setItem('darkMode', this.darkMode);
        document.body.classList.toggle('dark-mode');
    }
}
window.themeManager = new ThemeManager();

// Simple Audio Manager
